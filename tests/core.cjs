const assert=require('node:assert/strict');
require('../core.js');
const sheet=(headers,rows,source)=>({headers,rows:rows.map((r,i)=>Object.assign(r,{_row:i+2})),mapping:VCore.mapping(headers),source,formulas:new Set()});
const info=sheet(['姓名','学号'],[['甲','001'],['乙','002'],['丙','003'],['丁','004']],'info');
const score=sheet(['姓名','学号','总分(15)','闪电得分(10)','摄影得分(10)'],[['甲','001','12','9','9'],['乙','002','13','9','8'],['丙','003','11','8','9'],['丁','004','0','0','0']],'score');
let base=VCore.prepare([info],[score]);
let r=VCore.evaluate(base,{lightning:1,photo:1,ties:'all'});
assert.equal(r.counts.lightning,2);assert.equal(r.counts.photo,1);assert.equal(new Set(r.selected.map(x=>x.id)).size,4);
r=VCore.evaluate(base,{lightning:1,photo:1,ties:'strict'});assert.equal(r.selected.find(x=>x.id==='002').role,'小闪电');
r=VCore.evaluate(base,{lightning:1,photo:1,ties:'strict',priority:'photo'});assert.equal(r.selected.find(x=>x.id==='001').role,'摄影志愿者');
r=VCore.evaluate(base,{lightning:0,photo:0});assert.equal(r.counts.ordinary,4);
r=VCore.evaluate(base,{lightning:1,photo:1},{'002':{role:'exclude'}});assert(!r.selected.some(x=>x.id==='002'));
const blank=sheet(['姓名','学号','总分(15)','活动感想/了解（3）','活动思考/热情（4）','应变能力（3）','情景对话（3）','综合印象（2）'],[['戊','005','0','','','','','']],'blank');blank.formulas.add('2:2');
base=VCore.prepare([sheet(['姓名','学号'],[['戊','005']],'i')],[blank]);assert.equal(base.scores.size,0);
const a=sheet(['姓名','学号','总分(15)'],[['甲','001','10']],'a'),b=sheet(['姓名','学号','总分(15)'],[['甲','001','14']],'b');
base=VCore.prepare([info],[a,b]);r=VCore.evaluate(base,{lightning:0,photo:0});assert.equal(r.selected[0].general,12);
r=VCore.evaluate(base,{lightning:0,photo:0,duplicate:'highest'});assert.equal(r.selected[0].general,14);
base=VCore.prepare([sheet(['姓名','学号'],[['甲','001']],'i')],[sheet(['姓名','学号','总分(15)'],[['甲','901','12']],'s')]);
assert.equal(VCore.evaluate(base).selected.length,0);
assert.equal(VCore.evaluate(base,{}, {'001':{acceptName:true}}).selected[0].id,'001');
console.log('Passed: ties, strict quotas, priority, zero scores, exclusions, empty formulas, duplicate scores, explicit identity matching.');
